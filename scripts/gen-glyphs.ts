// Builds the OCR glyph templates (src/import/glyphs.ts) from the labelled demo screenshots.
// Usage: npx tsx scripts/gen-glyphs.ts
//
// Each screenshot's expected text is in src/import/ocr.fixtures.json. Its text line is split into
// glyphs and words (at wide gaps), each expected word is matched with a run of glyphs, and the glyphs
// for each character are averaged. Large (full-screen) and small (split-screen) text get separate
// templates. Small text can break a letter of "Position:" into pieces; such a label is skipped and only
// its numbers are learned.
// Also reports a leave-one-out check: each screenshot read with templates built without it.
import fs from "node:fs";
import jpeg from "jpeg-js";
import { type Glyph, type Line, WORD_GAP, findLines, glyphDistance, segment } from "../src/import/ocr";

type Template = { ch: string; wu: number; cells: number[] };
const fixtures: Record<string, string> = JSON.parse(fs.readFileSync("src/import/ocr.fixtures.json", "utf8"));

const lines = new Map<string, Line>();
for (const file of Object.keys(fixtures)) {
  const img = jpeg.decode(fs.readFileSync(`public/demo/${file}`), { useTArray: true });
  const line = findLines(img, 0, Math.round(img.width * 0.4))
    .map((b) => segment(img, b, 0, Math.round(img.width * 0.4)))
    .find((l) => l.glyphs.length >= fixtures[file].replace(/ /g, "").length);
  if (!line) throw new Error(`No text line found in ${file}`);
  lines.set(file, line);
}

/** Each expected character with its glyph: the label's only if it split into exactly its characters. */
function labelled(file: string): [string, Glyph][] {
  const [label, ...numbers] = fixtures[file].split(" "), line = lines.get(file)!;
  const words: Glyph[][] = [];
  line.glyphs.forEach((g, i) => (i === 0 || g.gap > WORD_GAP ? words.push([g]) : words.at(-1)!.push(g)));
  const firstNumber = words.findIndex((_, k) => k > 0 && numbers.every((n, j) => words[k + j]?.length === n.length));
  if (firstNumber < 0) throw new Error(`Can't match the numbers in ${file} with its glyphs`);
  const pair = (texts: string[], glyphRuns: Glyph[][]) =>
    texts.flatMap((text, j) => [...text].map((ch, i): [string, Glyph] => [ch, glyphRuns[j][i]]));
  const labelGlyphs = words.slice(0, firstNumber).flat();
  return [
    ...(labelGlyphs.length === label.length ? pair([label], [labelGlyphs]) : []),
    ...pair(numbers, words.slice(firstNumber, firstNumber + numbers.length)),
  ];
}

function build(files: string[]): Template[] {
  const groups = new Map<string, Glyph[]>();
  for (const file of files) {
    const line = lines.get(file)!, size = line.y1 - line.y0 + 1 < 14 ? "small" : "large";
    for (const [ch, g] of labelled(file)) {
      const k = `${ch}|${size}`;
      groups.set(k, [...(groups.get(k) ?? []), g]);
    }
  }
  return [...groups].map(([k, gs]) => ({
    ch: k.split("|")[0],
    wu: +(gs.reduce((s, g) => s + g.wu, 0) / gs.length).toFixed(3),
    cells: gs[0].cells.map((_, i) => +(gs.reduce((s, g) => s + g.cells[i], 0) / gs.length).toFixed(3)),
  }));
}

const read = (glyphs: Glyph[], templates: Template[]) =>
  glyphs.map((g) => templates.reduce((a, t) => (glyphDistance(g, t) < glyphDistance(g, a) ? t : a)).ch).join("");

let ok = 0;
for (const file of Object.keys(fixtures)) {
  const pairs = labelled(file), want = pairs.map(([ch]) => ch).join("");
  const got = read(pairs.map(([, g]) => g), build(Object.keys(fixtures).filter((f) => f !== file)));
  if (got === want) ok++;
  else console.log(`leave-one-out miss: ${file.slice(0, 16)} read "${got}" expected "${want}"`);
}
console.log(`leave-one-out: ${ok}/${Object.keys(fixtures).length} read exactly`);

const templates = build(Object.keys(fixtures)).sort((a, b) => a.ch.localeCompare(b.ch));
fs.writeFileSync("src/import/glyphs.ts", `// Generated by scripts/gen-glyphs.ts from the labelled demo screenshots. Do not edit by hand.
export const GLYPHS: { ch: string; wu: number; cells: number[] }[] = [
${templates.map((t) => `  { ch: ${JSON.stringify(t.ch)}, wu: ${t.wu}, cells: [${t.cells.join(",")}] },`).join("\n")}
];
`);
console.log(`wrote ${templates.length} templates for: ${[...new Set(templates.map((t) => t.ch))].join("")}`);
