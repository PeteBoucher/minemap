// Learns the Java Edition map frame (src/import/frameTemplate.ts) from screenshots whose map squares
// were measured by hand.
// Usage: npx tsx scripts/gen-frame-template.ts
//
// src/import/fixtures/java/crops.json gives each screenshot's map square in the 1280×720 frame. Each
// frame cell (one map pixel of the frame around the square) is sampled and divided by the frame's
// median brightness, so lighting cancels out; the template is the mean over the screenshots. Cells
// that vary a lot between screenshots are where scenery shows through the frame's ragged outer edge,
// and are left out. The other Java fixtures (2026-11-24_*, level4-*) are kept out on purpose, so the
// tests show the frame is found in screenshots it wasn't learned from.
// Also reports a leave-one-out check: each screenshot searched with a template learned without it.
import fs from "node:fs";
import jpeg from "jpeg-js";
import type { Crop } from "../src/core/terrain";
import { RING, RING_CELLS, RING_ROWS, TEMPLATE_CODE, TEMPLATE_MIN, TEMPLATE_STEP, findJavaMap, lumaPlane, parseTemplate, sample } from "../src/import/frame";
import { fitToFrame } from "../src/import/image";

const DIR = "src/import/fixtures/java/";
const crops: Record<string, Crop> = JSON.parse(fs.readFileSync(`${DIR}crops.json`, "utf8"));
/** Spread between screenshots (relative to the median) above which a cell is left out. */
const MAX_SPREAD = 0.12;

/** Each frame cell's brightness over the frame's median, averaged over 2×2 points in the cell. */
function cells(file: string): number[] {
  const img = fitToFrame(jpeg.decode(fs.readFileSync(DIR + file), { useTArray: true, maxMemoryUsageInMB: 1024 }));
  const L = lumaPlane(img), c = crops[file], p = c.size / 128;
  const at = (u: number, v: number) => sample(L, c.x + (u - RING) * p, c.y + (v - RING) * p);
  const raw = RING_CELLS.map(([u, v]) => (at(u + 0.25, v + 0.25) + at(u + 0.75, v + 0.25) + at(u + 0.25, v + 0.75) + at(u + 0.75, v + 0.75)) / 4);
  const median = [...raw].sort((a, b) => a - b)[raw.length >> 1];
  return raw.map((x) => x / median);
}

const all = new Map(Object.keys(crops).map((f) => [f, cells(f)]));

function build(files: string[]): string[] {
  const rows = files.map((f) => all.get(f)!);
  const chars = RING_CELLS.map((_, i) => {
    const xs = rows.map((r) => r[i]), mean = xs.reduce((a, b) => a + b, 0) / xs.length;
    const spread = Math.sqrt(xs.reduce((a, b) => a + (b - mean) ** 2, 0) / xs.length);
    if (spread > MAX_SPREAD) return " ";
    return TEMPLATE_CODE[Math.max(0, Math.min(TEMPLATE_CODE.length - 1, Math.round((mean - TEMPLATE_MIN) / TEMPLATE_STEP)))];
  });
  // one string per frame row: the full width at the top, then the left and right edges' cells
  const out: string[] = [];
  for (let v = 0, i = 0; v < RING_ROWS; v++) {
    const n = v < RING ? 128 + 2 * RING : 2 * RING;
    out.push(chars.slice(i, i + n).join(""));
    i += n;
  }
  return out;
}

let worst = 0;
for (const file of all.keys()) {
  const t = parseTemplate(build([...all.keys()].filter((f) => f !== file)));
  const img = fitToFrame(jpeg.decode(fs.readFileSync(DIR + file), { useTArray: true, maxMemoryUsageInMB: 1024 }));
  const got = findJavaMap(lumaPlane(img), t), want = crops[file];
  const err = got ? Math.max(...(["x", "y", "size"] as const).map((k) => Math.abs(got.crop[k] - want[k]))) : Infinity;
  worst = Math.max(worst, err);
  console.log(`leave-one-out: ${file} ${got ? `off by ${err} px (match ${got.match.toFixed(3)})` : "not found"}`);
}
console.log(`leave-one-out: worst ${worst} px (half a map pixel is about 2)`);

const rows = build([...all.keys()]);
const unused = rows.join("").split(" ").length - 1;
fs.writeFileSync("src/import/frameTemplate.ts", `// Generated by scripts/gen-frame-template.ts from the Java Edition screenshots in fixtures/java/crops.json. Do not edit by hand.
// The held map's frame, one letter per map pixel (see TEMPLATE_CODE in frame.ts): rows 0–${RING - 1} are the top edge,
// full width; the rest hold the left edge's ${RING} cells then the right edge's. Spaces (${unused} of ${RING_CELLS.length}): no stable value.
export const FRAME_ROWS: string[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`);
console.log(`wrote src/import/frameTemplate.ts (${RING_CELLS.length - unused} cells)`);
