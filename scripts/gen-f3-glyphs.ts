// Builds the F3 glyph bitmaps (src/import/f3Glyphs.ts) from labelled Java Edition screenshots.
// Usage: npx tsx scripts/gen-f3-glyphs.ts
//
// src/import/fixtures/java/f3.json gives, per screenshot, the text of its XYZ and Block lines. Each
// label is matched with the screenshot's text line that splits into the same words of the same
// lengths, and each glyph's bitmap is recorded as its character. A bitmap seen as two different
// characters is an error (a wrong label, or the cutting is off).
// Also reports a leave-one-out check: each screenshot read with bitmaps learned without it.
import fs from "node:fs";
import jpeg from "jpeg-js";
import { type F3Glyph, F3_WORD_GAP, f3Lines } from "../src/import/f3";

const DIR = "src/import/fixtures/java/";
const labels: Record<string, string[]> = JSON.parse(fs.readFileSync(`${DIR}f3.json`, "utf8"));

const words = (line: F3Glyph[]) => {
  const out: F3Glyph[][] = [];
  line.forEach((g, i) => (i === 0 || g.gap >= F3_WORD_GAP ? out.push([g]) : out.at(-1)!.push(g)));
  return out;
};

/** [character, bitmap] for every labelled glyph in a screenshot. */
function labelled(file: string): [string, string][] {
  const img = jpeg.decode(fs.readFileSync(DIR + file), { useTArray: true, maxMemoryUsageInMB: 1024 });
  const lines = f3Lines(img);
  return labels[file].flatMap((text) => {
    const want = text.split(" ");
    // the line's leading words must match the label's word lengths (a line can run on past the label)
    const line = lines.find((l) => { const w = words(l); return want.every((t, i) => w[i]?.length === t.length); });
    if (!line) throw new Error(`No line in ${file} splits like "${text}"`);
    const w = words(line);
    return want.flatMap((t, i) => [...t].map((ch, j): [string, string] => [ch, w[i][j].bitmap]));
  });
}

const all = new Map(Object.keys(labels).map((f) => [f, labelled(f)]));

function build(files: string[]): Record<string, string> {
  const map: Record<string, string> = {};
  for (const f of files) for (const [ch, bm] of all.get(f)!) {
    if (map[bm] && map[bm] !== ch) throw new Error(`${f}: bitmap read as both "${map[bm]}" and "${ch}"\n${bm.split("/").join("\n")}`);
    map[bm] = ch;
  }
  return map;
}

let ok = 0;
for (const file of all.keys()) {
  const map = build([...all.keys()].filter((f) => f !== file)), pairs = all.get(file)!;
  const got = pairs.map(([, bm]) => map[bm] ?? "?").join(""), want = pairs.map(([ch]) => ch).join("");
  if (got === want) ok++;
  else console.log(`leave-one-out miss: ${file} read "${got}" expected "${want}"`);
}
console.log(`leave-one-out: ${ok}/${all.size} read exactly`);

const map = build([...all.keys()]);
const entries = Object.entries(map).sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));
fs.writeFileSync("src/import/f3Glyphs.ts", `// Generated by scripts/gen-f3-glyphs.ts from the labelled Java Edition screenshots. Do not edit by hand.
// Each key is a glyph's font-pixel bitmap (rows joined by "/", "#" for ink).
export const F3_GLYPHS: Record<string, string> = {
${entries.map(([bm, ch]) => `  ${JSON.stringify(bm)}: ${JSON.stringify(ch)},`).join("\n")}
};
`);
console.log(`wrote ${entries.length} bitmaps for: ${[...new Set(entries.map(([, ch]) => ch))].sort().join("")}`);
